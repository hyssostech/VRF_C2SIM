# ---------------------------------------------------------------------------
# (a) the duration rewrite - a pure function, self-tested below
# ---------------------------------------------------------------------------
C2SIM_DURATION = re.compile(
    r'^P[0-9]{2}Y[0-9]{2}M[0-9]{2}DT[0-9]{2}H[0-9]{2}M[0-9]{2}S$')

# canonical ISO-8601: PnYnMnDTnHnMnS with any field omitted. Fractions are NOT accepted -
# the C2SIM pattern has no room for them, so silently truncating one would change a value.
ISO_8601 = re.compile(
    r'^P(?:([0-9]+)Y)?(?:([0-9]+)M)?(?:([0-9]+)D)?'
    r'(?:T(?:([0-9]+)H)?(?:([0-9]+)M)?(?:([0-9]+)S)?)?$')


def to_c2sim_duration(value):
    """Rewrite an ISO-8601 duration into the C2SIM 1.1 pattern form.

    Already-conforming values are returned unchanged. Anything that cannot be read as a
    whole-number ISO-8601 duration, or whose fields do not fit two digits, raises - the
    point of this script is that a format it does not understand STOPS it, rather than
    being passed through to produce a plausible wrong time.
    """
    v = (value or '').strip()
    if C2SIM_DURATION.match(v):
        return v
    m = ISO_8601.match(v)
    if not m or v in ('P', 'PT'):
        raise ValueError('not an ISO-8601 duration this script can rewrite: %r' % value)
    y, mo, d, h, mi, s = (int(g) if g else 0 for g in m.groups())
    for label, n in (('years', y), ('months', mo), ('days', d),
                     ('hours', h), ('minutes', mi), ('seconds', s)):
        if n > 99:
            raise ValueError('%s=%d does not fit the C2SIM two-digit field in %r'
                             % (label, n, value))
    return 'P%02dY%02dM%02dDT%02dH%02dM%02dS' % (y, mo, d, h, mi, s)


def rewrite_durations(text):
    """Rewrite every IsoTimeDuration element value in place. Returns (text, changes)."""
    changes = []

    def sub(m):
        old = m.group(1)
        new = to_c2sim_duration(old)
        if new != old:
            changes.append((old, new))
        return '<IsoTimeDuration>%s</IsoTimeDuration>' % new

    out = re.sub(r'<IsoTimeDuration>([^<]*)</IsoTimeDuration>', sub, text)
    return out, changes


