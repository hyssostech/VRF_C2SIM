def gate(text, label, problems):
    """Every hazard this project has actually been bitten by, checked on the OUTPUT."""
    # ASCII only (control characters included - a stray VT/BEL is not printable ASCII)
    bad = [(i, c) for i, c in enumerate(text)
           if not (c in '\t\r\n' or ' ' <= c <= '~')]
    if bad:
        problems.append('%s: %d non-ASCII/control byte(s), first at offset %d (0x%02X)'
                        % (label, len(bad), bad[0][0], ord(bad[0][1])))
    # CRLF class preserved: no lone LF, no lone CR
    if re.search(r'(?<!\r)\n', text):
        problems.append('%s: a bare LF (the export is 100%% CRLF)' % label)
    if re.search(r'\r(?!\n)', text):
        problems.append('%s: a stray CR' % label)
    # STP-830: the SDK takes the first '<'+letter in the TEXT - comments included - as the
    # message root. Nothing may precede MessageBody, and no comment may hold such a token.
    first = re.search(r'<[A-Za-z_]', text)
    if not first or not text.startswith('<?xml', 0) or text[first.start():first.start() + 12] != '<MessageBody':
        problems.append('%s: the first "<word" token is not <MessageBody' % label)
    for c in re.findall(r'<!--(.*?)-->', text, re.S):
        if re.search(r'<[A-Za-z_]', c):
            problems.append('%s: an XML comment carries a "<word" token: %r' % (label, c[:60]))
    # well-formed, right root, right namespace
    try:
        root = ET.fromstring(text)
    except Exception as exc:                                   # noqa: BLE001
        problems.append('%s: not well-formed XML: %s' % (label, exc))
        return
    if root.tag != Q + 'MessageBody':
        problems.append('%s: root is %s, expected %sMessageBody' % (label, root.tag, Q))
    for v in re.findall(r'<IsoTimeDuration>([^<]*)</IsoTimeDuration>', text):
        if not C2SIM_DURATION.match(v):
            problems.append('%s: IsoTimeDuration %r still violates the C2SIM pattern'
                            % (label, v))


def sha(data):
    return hashlib.sha256(data if isinstance(data, bytes)
                          else data.encode('utf-8')).hexdigest()


def read(path):
    with open(path, 'r', encoding='utf-8', newline='') as fh:
        return fh.read()


def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='') as fh:
        fh.write(text)


