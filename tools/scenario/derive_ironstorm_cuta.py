def derive_order(src_text, log):
    """Apply (a), (b) and (c) to the order text. Returns the derived text."""
    blocks = TASK_BLOCK.findall(src_text)
    log('order carries %d <Task> blocks' % len(blocks))
    if len(blocks) != src_text.count('<Task>'):
        raise AssertionError('the Task-block scanner missed %d of %d blocks'
                             % (src_text.count('<Task>') - len(blocks),
                                src_text.count('<Task>')))

    by_uuid = {}
    for b in blocks:
        u = task_uuid(b)
        if u is None:
            raise AssertionError('a <Task> block carries no <UUID>')
        if u in by_uuid:
            raise AssertionError('duplicate task uuid %s' % u)
        by_uuid[u] = b

    missing = sorted(set(KEEP) - set(by_uuid))
    if missing:
        raise AssertionError('the export no longer carries kept task(s): %s'
                             % ', '.join(missing))

    # (c) chain integrity: every kept task's predecessor must also be kept.
    for u in KEEP:
        m = re.search(r'<TemporalAssociationWithAction>([^<]+)<', by_uuid[u])
        pred = m.group(1).strip() if m else None
        if pred and pred not in KEEP:
            raise AssertionError('kept task %s (%s) depends on dropped task %s'
                                 % (KEEP[u], u, pred))
        log('  keep %s %s  predecessor=%s' % (KEEP[u], u, KEEP.get(pred, '-')))

    # (b) verify each added graphic EXISTS in the order, is a Point, and carries the Name
    # this script expects; then verify the task does not already reference it.
    for task_u, (g_uuid, g_name, _short) in ADD_GRAPHIC.items():
        at = src_text.find('<UUID>%s</UUID>' % g_uuid)
        if at < 0:
            raise AssertionError('graphic %s is not in the order' % g_uuid)
        start = src_text.rfind('<TacticalGraphic>', 0, at)
        end = src_text.find('</TacticalGraphic>', at)
        blk = src_text[start:end]
        if '<Point>' not in blk:
            raise AssertionError('graphic %s is not a <Point>' % g_uuid)
        nm = re.search(r'<Name>([^<]*)</Name>', blk)
        if not nm or nm.group(1).strip() != g_name:
            raise AssertionError('graphic %s Name is %r, expected %r'
                                 % (g_uuid, nm.group(1) if nm else None, g_name))
        if g_uuid in by_uuid[task_u]:
            raise AssertionError('task %s already references %s' % (KEEP[task_u], g_uuid))
        lat = re.search(r'<Latitude>([^<]*)</Latitude>', blk)
        lon = re.search(r'<Longitude>([^<]*)</Longitude>', blk)
        log('  add  %s -> %s  %s  @ %s, %s'
            % (KEEP[task_u], g_uuid, g_name[:34], lat.group(1), lon.group(1)))

    # Build the derived text: walk the ORIGINAL string, copying everything, replacing the
    # kept task blocks with their edited form and deleting the rest. Working on the raw
    # string (never on a re-serialized tree) is what keeps every untouched byte identical.
    out = []
    pos = 0
    kept = dropped = 0
    for m in TASK_BLOCK.finditer(src_text):
        out.append(src_text[pos:m.start()])
        pos = m.end()
        block = m.group(0)
        u = task_uuid(block)
        if u not in KEEP:
            dropped += 1
            continue
        if u in ADD_GRAPHIC:
            g_uuid, _g_name, short = ADD_GRAPHIC[u]
            block = insert_map_graphic(block, g_uuid, short)
        out.append(block)
        kept += 1
    out.append(src_text[pos:])
    text = ''.join(out)
    log('kept %d task(s), dropped %d' % (kept, dropped))
    if kept != len(KEEP):
        raise AssertionError('kept %d tasks, expected %d' % (kept, len(KEEP)))

    # (e) the water nudge, on the assembled document so the site count is the DERIVED
    # file's and not the export's.
    text = apply_water_nudge(text, log)

    # (a) last, so it covers the whole derived document including nothing new (the
    # inserted lines carry no duration).
    text, changes = rewrite_durations(text)
    log('rewrote %d IsoTimeDuration value(s)' % len(changes))
    seen = {}
    for old, new in changes:
        seen.setdefault((old, new), 0)
        seen[(old, new)] += 1
    for (old, new), n in sorted(seen.items()):
        log('  %-6s -> %-22s x%d' % (old, new, n))
    return text


def derive_init(src_text, log):
    """The init needs NO change: it carries no IsoTimeDuration (verified here, not
    assumed), no task, and its SystemName is left exactly as exported - (d). The derived
    file is therefore a byte-identical copy under the cut's own name."""
    n = len(re.findall(r'<IsoTimeDuration>', src_text))
    if n:
        raise AssertionError('the init now carries %d IsoTimeDuration value(s); change '
                             '(a) would have to be applied to it too' % n)
    sysname = re.findall(r'<SystemName>([^<]*)</SystemName>', src_text)
    log('init SystemName %r - LEFT AS EXPORTED (d, STP-847)' % (sysname or [None])[0])
    log('init carries no IsoTimeDuration; derived init is a byte-identical copy')
    return src_text


def selftest():
    ok = True

    def check(label, got, want):
        nonlocal ok
        if got != want:
            ok = False
            print('  MISMATCH %-46s got %r want %r' % (label, got, want))
        else:
            print('  ok       %-46s %r' % (label, got))

    print('to_c2sim_duration:')
    check('PT20M', to_c2sim_duration('PT20M'), 'P00Y00M00DT00H20M00S')
    check('PT30M', to_c2sim_duration('PT30M'), 'P00Y00M00DT00H30M00S')
    check('PT50M', to_c2sim_duration('PT50M'), 'P00Y00M00DT00H50M00S')
    check('PT10M', to_c2sim_duration('PT10M'), 'P00Y00M00DT00H10M00S')
    check('PT0S', to_c2sim_duration('PT0S'), 'P00Y00M00DT00H00M00S')
    check('PT1H30M', to_c2sim_duration('PT1H30M'), 'P00Y00M00DT01H30M00S')
    check('P1DT2H', to_c2sim_duration('P1DT2H'), 'P00Y00M01DT02H00M00S')
    check('idempotent', to_c2sim_duration('P00Y00M00DT00H20M00S'), 'P00Y00M00DT00H20M00S')
    for bad in ('', 'PT20', '20M', 'PT1.5S', 'PT100M', 'P', 'PT', 'nonsense'):
        try:
            to_c2sim_duration(bad)
            ok = False
            print('  MISMATCH %-46s accepted a value it must refuse' % repr(bad))
        except ValueError:
            print('  ok       refused %r' % bad)

    print('gate (proven on a DIRTY control first, per the ASCII rule):')
    good = ('<?xml version="1.0" encoding="utf-8"?>\r\n<MessageBody xmlns="%s">\r\n'
            '  <A>x</A>\r\n</MessageBody>' % NS)
    for label, sample, must_fire in [
            ('clean sample', good, False),
            # chr(), not a literal: THIS FILE IS ASCII-ONLY and must stay so,
            # while the control it builds has to be genuinely dirty or the gate
            # would pass vacuously.
            ('non-ASCII em dash',
             good.replace('<A>x', '<A>' + chr(0x2014)), True),
            ('NBSP', good.replace('<A>x', '<A>' + chr(0x00A0)), True),
            ('bare LF', good.replace('\r\n', '\n', 1), True),
            ('stray CR', good.replace('<A>', '\r<A>'), True),
            ('comment with a tag token', good.replace('  <A>', '  <!--<Task-->\r\n  <A>'), True),
            ('comment before the root', '<!--<x-->\r\n' + good, True)]:
        problems = []
        gate(sample, label, problems)
        fired = bool(problems)
        if fired != must_fire:
            ok = False
            print('  MISMATCH %-46s fired=%s want=%s %s'
                  % (label, fired, must_fire, problems[:1]))
        else:
            print('  ok       %-46s fired=%s' % (label, fired))

    print('SELFTEST %s' % ('PASSED' if ok else 'FAILED'))
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true',
                    help='derive and verify, but write nothing; non-zero if the files '
                         'on disk differ from what the script would write')
    ap.add_argument('--selftest', action='store_true',
                    help='run the pure-function tests and exit')
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()

    def log(msg):
        print(msg)

    src_order = read(SRC_ORDER)
    src_init = read(SRC_INIT)
    log('INPUT  %s  sha256 %s' % (os.path.basename(SRC_INIT), sha(src_init)))
    log('INPUT  %s  sha256 %s' % (os.path.basename(SRC_ORDER), sha(src_order)))
    log('')
    out_order = derive_order(src_order, log)
    out_init = derive_init(src_init, log)
    log('')

    problems = []
    gate(out_order, 'derived order', problems)
    gate(out_init, 'derived init', problems)
    if problems:
        for p in problems:
            print('GATE FAILURE: %s' % p)
        return 2
    log('gates: ASCII, CRLF, STP-830 comment scan, well-formedness, root, namespace, '
        'duration pattern - ALL PASS')

    for path, text in ((OUT_INIT, out_init), (OUT_ORDER, out_order)):
        name = os.path.basename(path)
        if args.check:
            if not os.path.exists(path):
                print('CHECK FAILURE: %s does not exist' % name)
                return 3
            if read(path) != text:
                print('CHECK FAILURE: %s on disk differs from the derivation' % name)
                return 3
            log('CHECK  %s  matches  sha256 %s' % (name, sha(text)))
        else:
            write(path, text)
            log('OUTPUT %s  sha256 %s  (%d bytes)'
                % (name, sha(text), len(text.encode('utf-8'))))
    return 0


if __name__ == '__main__':
    sys.exit(main())
