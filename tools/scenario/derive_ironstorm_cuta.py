#!/usr/bin/env python3
"""Derive the IRON STORM "CUT A" demo pair from the user's authoritative STP export.

WHY THIS IS A SCRIPT AND NOT A HAND EDIT
    The export is regenerated by STP whenever the plan changes. Every change this cut
    needs is mechanical, so it is expressed here once and re-applied on demand: re-run
    the script after a re-export and the derived pair is rebuilt, or the script FAILS
    LOUDLY because an assumption it depends on (a uuid, a task, an element order) no
    longer holds. It never edits in place and never guesses.

INPUTS  (byte-exact, never modified)
    data/STP-IRON-STORM-SYNTHETIC_Initialization.xml
    data/STP-IRON-STORM-SYNTHETIC_Order.xml
OUTPUTS (tracked)
    data/IRONSTORM_CUTA_Initialization.xml
    data/IRONSTORM_CUTA_Order.xml

THE COMPLETE CHANGE LIST - nothing else is touched. Exactly ONE coordinate pair moves
(change (e), a user ruling); no unit is renamed, no TaskActionCode is altered, no graphic
is added or removed, no comment is rewritten, and the root element + namespace + CRLF line
endings are preserved byte for byte. See data/IRONSTORM_CUTA_CHANGES.md for the rationale
and the consequences.

  (a) DURATION FORMAT (connector bug STP-848). Every IsoTimeDuration value is rewritten
      from the canonical-ISO short form the export writes ("PT20M") to the C2SIM 1.1
      pattern form ("P00Y00M00DT00H20M00S"). The schema's IsoTimeDurationBaseType is an
      xs:string restricted by
        [P]{1}[0-9]{2}[Y]{1}[0-9]{2}[M]{1}[0-9]{2}[D]{1}T{1}[0-9]{2}[H]{1}[0-9]{2}[M]{1}[0-9]{2}[S]{1}
      (C2SIM_SMX_LOX_CWIX2024.xsd:17-24) - every field present, two digits wide. The
      short form is NOT valid C2SIM 1.1, and OrderParser.FindTotalIsoMs refuses it
      (returns -1 -> DurationMs 0), which is what leaves the export's HoldInPlace tasks
      MALFORMED and their STREND successors waiting out the gate. This rewrite changes
      no VALUE - only the spelling. 46 values in the order; the init carries none.

  (b) TWO MapGraphicID REFERENCES ADDED, to existing graphics the order ALREADY carries.
      No new geometry is authored.
        T02 (28ID, ATTACK)     -> c8cde9b6-17f7-f253-800e-4de0cae84db3
                                  PassagePoint_28ID_SLOT0
        T10 (1-112 IN, CRESRV) -> cc23071f-aa60-9f52-884c-11505051cc99
                                  PassagePoint_48_IBCT_SLOT0
      Both tasks carry NO geometry at all in the export, so both execute in place and
      the cut has nothing to watch. MapGraphicID is inserted immediately before Name,
      which is where the schema's ActionGroup sequence puts it.

  (c) THE ORDER IS REDUCED to the CUT-3 task set plus the predecessors its temporal
      chains need. KEPT: T01 -> T02 (28ID), T10 (1-112 IN, a chain root), T13 -> T14
      (48 IBCT). DROPPED: the other 18 tasks. Chain integrity is ASSERTED, not assumed:
      every kept task's ActionTemporalRelationship/TemporalAssociationWithAction must
      name a task that is also kept, or the script fails.

  (d) SystemName IS LEFT AS EXPORTED ("Not Set" - connector bug STP-847). The run passes
      --client-id "Not Set" so that the interface's own ClientId filter matches. This is
      deliberately NOT papered over in the data: the defect belongs on the producer side
      and the data file is the evidence.

  (e) T14's DESTINATION IS MOVED 799 m DUE WEST, out of a lake - the ONE coordinate this
      script changes. USER RULING 2026-09-21 ("as recommended"); STP will not re-author it.
        BEFORE  54.04034819271516 / 23.336444730300467
        AFTER   54.040348        / 23.324206
      The authored leg crosses CLCplus class 100 (preset="Water") for 1,565 m of its
      2,757 m, and deep-water is acceleration-factor 0.000000, so the unit would stop dead
      with the task reported TaskRunning for ever. Applied to the graphic the interface
      actually drives AND to T14's mirrored embedded Location - see apply_water_nudge.
      NO OTHER COORDINATE MOVES.

USAGE
    python tools/scenario/derive_ironstorm_cuta.py                 # write the pair
    python tools/scenario/derive_ironstorm_cuta.py --check         # verify, write nothing
    python tools/scenario/derive_ironstorm_cuta.py --selftest      # pure-function tests

The script is deterministic: the same inputs always produce byte-identical outputs, and
it prints the SHA-256 of every input and output so a derivation can be audited later.
"""

